"""Optional font preparation; not part of the website build.

Install fonttools[woff] separately, then run with the directory containing
the upstream LXGW975YuanSC-500W.ttf and LXGW975YuanSC-700W.ttf files.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'src/assets/fonts/975yuan'
SOURCE = Path(sys.argv[1])


def unicode_ranges(points):
    ranges = []
    start = end = None
    for point in sorted(points):
        if end is not None and point == end + 1:
            end = point
            continue
        if start is not None:
            ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
        start = end = point
    if start is not None:
        ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ', '.join(ranges)


def prepare(weight):
    source = SOURCE / f'LXGW975YuanSC-{weight}W.ttf'
    with TTFont(source) as font:
        supported = set(font.getBestCmap())
    # A small shared file covers today's text. Remaining glyphs stay available
    # in independent blocks, so future articles do not need a font rebuild.
    core = supported & common
    remaining = supported - core
    groups = [('core', core)] + [
        (f'{block:X}', {cp for cp in remaining if cp // 1024 == block})
        for block in sorted({cp // 1024 for cp in remaining})
    ]
    faces = []
    for name, points in groups:
        font = TTFont(source)
        options = subset.Options()
        options.name_IDs = ['*']
        options.name_legacy = True
        options.name_languages = ['*']
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        font.flavor = 'woff2'
        filename = f'975yuan-{weight}-{name}.woff2'
        font.save(DEST / filename)
        font.close()
        faces.append(
            "@font-face {\n  font-family: 'LXGW 975 Yuan';\n"
            f"  src: url('../assets/fonts/975yuan/{filename}') format('woff2');\n"
            "  font-style: normal;\n"
            f"  font-weight: {'400 500' if weight == 500 else '600 900'};\n"
            "  font-display: swap;\n"
            f"  unicode-range: {unicode_ranges(points)};\n}}\n"
        )
    print(f'{weight}: {len(core)} core glyphs, {len(groups)} files', flush=True)
    return '\n'.join(faces)


common = set(range(0x20, 0x100))
for path in (ROOT / 'src').rglob('*'):
    if path.suffix in {'.md', '.astro', '.svelte', '.ts'}:
        common.update(ord(char) for char in path.read_text(encoding='utf-8'))

DEST.mkdir(parents=True, exist_ok=True)
with ThreadPoolExecutor(max_workers=2) as pool:
    css = list(pool.map(prepare, (500, 700)))
(ROOT / 'src/styles/fonts.css').write_text(
    '/* Generated by scripts/prepare-fonts.py; see the font directory license. */\n'
    + '\n'.join(css), encoding='utf-8'
)
